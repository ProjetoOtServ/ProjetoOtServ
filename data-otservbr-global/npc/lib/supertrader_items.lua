-- Helper function to get sell price
function GetSuperTraderSellPrice(clientId)
	for _, item in ipairs(SUPERTRADER_ITEMS.all) do
		if item.clientId == clientId then
			return item.sell
		end
	end
	return nil
end

-- Helper function to check if item is buyable
function IsSuperTraderBuyable(clientId)
	return GetSuperTraderSellPrice(clientId) ~= nil
end

